// падежи «свободен/занят», сетка пар. Раньше это было продублировано в js/core.js,
// lib/slots.js и lib/digest.js, и совпадение приходилось проверять отдельным тестом.
//
// Обычный (не ES-module) файл, чтобы работать и в браузере <script>, и через require() на
// сервере: в браузере кладёт себя в window.PEOPLE, в Node экспортирует через module.exports.
// Групповые ID вуза сюда НЕ входят — они используются только сервером в api/schedule.js
// и нигде не дублируются, переносить их значит зря усложнять.
(function (root) {
  var PEOPLE = {
    me: {
      name: 'Кирилл',
      free: 'свободен',
      busy: 'занят',
      slots: [['08:00', '09:30'], ['09:40', '11:10'], ['11:50', '13:20'], ['13:30', '15:00'], ['15:40', '17:10'], ['17:20', '18:50']],
    },
    her: {
      name: 'Маша',
      free: 'свободна',
      busy: 'занята',
      slots: [['08:30', '10:05'], ['10:15', '11:50'], ['12:00', '13:35'], ['14:15', '15:50'], ['16:00', '17:35']],
    },
  };
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = PEOPLE;
  } else {
    root.PEOPLE = PEOPLE;
    (root.PARTS = root.PARTS || []).push('config'); // для проверки неполной заливки в index.html
  }
})(typeof window !== 'undefined' ? window : globalThis);
