  const rSwap = d(swapNew, swapOld);
  ok('две одинаковые пары в неделе переставлены — обе распознаны как «Перенесена» (сопоставление по порядку времени)',
    rSwap.length === 2 && rSwap.every((e) => e.type === 'moved') && rSwap.find((e) => e.was.d === '2026-09-22').now.d === '2026-09-23' && rSwap.find((e) => e.was.d === '2026-09-24').now.d === '2026-09-25', rSwap);

  // B) Известное ограничение эвристики: одна пара отменена и НЕЗАВИСИМО добавлена ещё одна пара
  //    того же предмета/типа в ту же неделю — алгоритм не может отличить это от переноса и
  //    честно покажет «Перенесена», хотя по смыслу это могли быть два разных события.
  //    Тест фиксирует ТЕКУЩЕЕ поведение, а не одобряет его как единственно верное — если он
  //    когда-нибудь начнёт падать, это сигнал посмотреть на эвристику осознанно, а не молча её поменять.
