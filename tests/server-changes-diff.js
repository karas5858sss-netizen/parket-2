  const susOk = (name, a, b, expect) => ok(`подозрительно: ${a} → ${b} (${name})`, C.isSuspicious(snapN(a), snapN(b), TODAY) === expect);
  susOk('чуть меньше 40% — подозрительно', 10, 3, true);
  susOk('ровно 40% — уже не подозрительно (строгое <)', 10, 4, false);
  susOk('с запасом больше 40% — не подозрительно', 10, 5, false);
  susOk('11 → 4 (чуть больше 40%×11=4.4) — подозрительно', 11, 4, true);
  susOk('20 → 7 (меньше 8.0) — подозрительно', 20, 7, true);
  susOk('20 → 8 (ровно 40%) — не подозрительно', 20, 8, false);
  susOk('1 → 0 — подозрительно всегда (даже при a<10)', 1, 0, true);
  susOk('9 → 0 — подозрительно (первое условие не требует a>=10)', 9, 0, true);
