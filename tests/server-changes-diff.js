  //    алгоритм сопоставляет по порядку времени (Пн→Вт, Чт→Пт), результат ожидаемо верный.
  const swapOld = [L(1, '2026-09-22', '10:00', '11:00', 'Физра', 'пр'), L(2, '2026-09-24', '14:00', '15:00', 'Физра', 'пр')]; // Вт, Чт
