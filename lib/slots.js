// lib/slots.js — сетка пар у каждого. КОПИЯ ЕСТЬ В index.html (константа SLOTS): менять в обоих местах.
// Номер пары определяется по времени начала.

const SLOTS = {
  me: [['08:00', '09:30'], ['09:40', '11:10'], ['11:50', '13:20'], ['13:30', '15:00'], ['15:40', '17:10'], ['17:20', '18:50']],
  her: [['08:30', '10:05'], ['10:15', '11:50'], ['12:00', '13:35'], ['14:15', '15:50'], ['16:00', '17:35']],
};

// Номер пары: по сетке, иначе номер из расписания вуза, иначе 0 (не нумеруется).
function pairNo(profile, l) {
  const i = (SLOTS[profile] || []).findIndex((s) => s[0] === l.start);
  if (i >= 0) return i + 1;
  return !l.custom && l.num > 0 ? l.num : 0;
}

module.exports = { SLOTS, pairNo };
